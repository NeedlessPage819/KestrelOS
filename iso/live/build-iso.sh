#!/usr/bin/env bash
# Builds the Kestrel OS live ISO (DECISIONS.md D22). Runs inside a Fedora container started
# by ../../build.sh with:
#   /rootfs   the live image (image/live), mounted read-only
#   /oci      the plain Kestrel image as an OCI directory: the installer's payload
#   /src      this directory (boot menu theme sources)
#   /output   where the ISO goes
# and ISO_LABEL, ISO_NAME and OS_NAME in the environment.
#
# Adapted from Titanoboa's build_iso.sh (https://github.com/ublue-os/titanoboa, Apache-2.0,
# commit 5c457c3d0518bd17e754be0fd98a60d29d26abb4). Kestrel additions: the boot menu theme,
# German menu entries drawn as images, the installer payload next to the squashfs, and a media checksum.
set -euo pipefail
: "${ISO_LABEL:?}" "${ISO_NAME:?}" "${OS_NAME:?}"

dnf5 -y -q install squashfs-tools xorriso mtools dosfstools isomd5sum \
    grub2-tools-extra librsvg2-tools rsms-inter-fonts python3

work=/work
root=$work/iso-root
rm -rf "$work"
mkdir -p "$root/images/pxeboot" "$root/LiveOS" "$root/boot/grub2" "$work/EFI"

# Live system. sysroot and ostree are the deployment machinery of the image, not files the
# live session uses.
mksquashfs /rootfs "$root/LiveOS/squashfs.img" -all-root -noappend -e sysroot -e ostree \
    -comp zstd -Xcompression-level "${SQUASHFS_LEVEL:-19}"

cp /rootfs/usr/lib/modules/*/initramfs.img "$root/images/pxeboot/initrd.img"
cp /rootfs/usr/lib/modules/*/vmlinuz "$root/images/pxeboot/vmlinuz"

# Signed boot chain from the image itself (shim, cdboot GRUB): Secure Boot keeps working.
cp -aT /rootfs/boot/efi/EFI "$work/EFI"

# Boot menu theme.
theme=$root/boot/grub2/themes/kestrel
mkdir -p "$theme"
python3 /src/grub_theme.py "$theme" "$OS_NAME"

# No nouveau in the live session (DECISIONS.md D25): on GTX 16xx and newer it often leaves
# Plasma black with only a cursor. Nvidia cards get the firmware picture or, from GTX 16xx
# on, the official driver (image/live: kestrel-live-gpu). Other graphics are not affected.
kernel_args="root=live:CDLABEL=$ISO_LABEL rd.live.image quiet rhgb enforcing=0"
kernel_args+=" rd.driver.blacklist=nouveau,nova_core modprobe.blacklist=nouveau,nova_core"
grub_cfg=$(cat <<EOF
# Kestrel OS live ISO boot menu (DECISIONS.md D22). Generated by iso/live/build-iso.sh.
set timeout=10
set default=0
set menu_auto_hide=false
search --no-floppy --set=root -l '$ISO_LABEL'

# Graphical menu with the Kestrel theme. With Secure Boot GRUB cannot load modules or
# fonts; the modules needed are built into Fedora's signed GRUB, and all text is in images.
insmod all_video
insmod gfxterm
insmod png
set gfxmode=auto
set gfxpayload=keep
terminal_output gfxterm
set theme=(\$root)/boot/grub2/themes/kestrel/theme.txt
export theme
insmod gzio
insmod part_gpt

# Entry labels are pictures (the class icons from grub_theme.py): GRUB cannot load fonts
# under Secure Boot. The titles are drawn transparent by the theme; they only show if the
# theme fails to load, so they avoid umlauts (GRUB's built-in font has none).
menuentry '$OS_NAME starten' --class start --id start {
  linux /images/pxeboot/vmlinuz $kernel_args
  initrd /images/pxeboot/initrd.img
}
menuentry '$OS_NAME starten (einfache Grafik)' --class basic --id basic {
  linux /images/pxeboot/vmlinuz $kernel_args nomodeset
  initrd /images/pxeboot/initrd.img
}
menuentry 'USB-Stick pruefen und starten' --class check --id check {
  linux /images/pxeboot/vmlinuz $kernel_args rd.live.check
  initrd /images/pxeboot/initrd.img
}
menuentry 'UEFI-Firmware-Einstellungen' --class firmware --id firmware {
  fwsetup
}
EOF
)
for dir in "$work"/EFI/* "$root/boot/grub2"; do
    printf '%s\n' "$grub_cfg" >"$dir/grub.cfg"
done
cp -aT "$work/EFI" "$root/EFI"

# FAT image for UEFI boot.
truncate -s 100M "$work/uefi.img"
mkfs.fat -F32 "$work/uefi.img" >/dev/null
mcopy -i "$work/uefi.img" -s "$work/EFI" ::

# Writable FAT partition for the live session's logs (DECISIONS.md D30, image/live:
# kestrel-live-log). On a USB stick Windows shows it as the drive "KESTRELLOG".
truncate -s 64M "$work/log.img"
mkfs.fat -F32 -n KESTRELLOG "$work/log.img" >/dev/null
echo "Kestrel OS live logs: one folder per boot, written by the live session." >"$work/README.txt"
mcopy -i "$work/log.img" "$work/README.txt" ::

# The installer payload is grafted in from /oci instead of copied (it is several GB).
xorriso -as mkisofs \
    -R -J -joliet-long \
    -V "$ISO_LABEL" \
    -partition_offset 16 \
    -appended_part_as_gpt \
    -append_partition 2 C12A7328-F81F-11D2-BA4B-00A0C93EC93B "$work/uefi.img" \
    -append_partition 3 EBD0A0A2-B9E5-4433-87C0-68B6B72699C7 "$work/log.img" \
    -iso_mbr_part_type EBD0A0A2-B9E5-4433-87C0-68B6B72699C7 \
    -e --interval:appended_partition_2:all:: \
    -no-emul-boot \
    -iso-level 3 \
    -graft-points \
    -o "/output/$ISO_NAME" \
    "/=$root" "/container=/oci"

# Checksum for the "check USB stick" menu entry (rd.live.check).
implantisomd5 "/output/$ISO_NAME"
rm -rf "$work"
