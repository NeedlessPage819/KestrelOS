#!/usr/bin/env python3
"""Generates the Kestrel GRUB theme for the live ISO boot menu (DECISIONS.md D22).

Dark like the Mac's startup screens: the white Kestrel mark and name on near-black, a short
centred menu whose selected entry sits on a soft rounded highlight, and a hint line.

All text is drawn into images. With Secure Boot, GRUB refuses to load font files (font
parsing was once a security hole), and its built-in font has no umlauts. So the menu entries
are pictures: each entry has an empty title and shows its label as its class icon. The
menu looks the same with and without Secure Boot. (The titles stay as a text fallback in
case the theme fails, drawn transparent here.)

Usage: grub_theme.py OUTPUT_DIR OS_NAME
"""
import subprocess
import sys
from pathlib import Path

W, H = 1920, 1080                        # background is scaled by GRUB to the screen
MARK = ("M1 6.2 C3.4 4.2 5.9 4.4 8 7.6 C10.1 4.4 12.6 4.2 15 6.2 "
        "C12.4 5.9 10.2 7.2 8 11.2 C5.8 7.2 3.6 5.9 1 6.2 Z")     # kestrel-logo-symbolic.svg
R = 12                                   # corner radius of the selection highlight
HIGHLIGHT = 'fill="#ffffff" fill-opacity="0.14"'
LABEL_W, LABEL_H = 460, 48               # entry label images (pixels, not scaled by GRUB)

# Menu entries: GRUB class (used by iso/live/build-iso.sh) and the label shown.
ENTRIES = {
    "start": "Start {os}",
    "basic": "Start {os} (basic graphics)",
    "check": "Check USB stick and start",
    "firmware": "UEFI firmware settings",
}


def render(svg, out, w, h):
    subprocess.run(["rsvg-convert", "-w", str(w), "-h", str(h), "-o", str(out)],
                   input=svg.encode(), check=True)


def background(os_name):
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}">
  <defs><radialGradient id="g" cx="0.5" cy="0.35" r="0.8">
    <stop offset="0" stop-color="#1d1c22"/><stop offset="1" stop-color="#050506"/>
  </radialGradient></defs>
  <rect width="{W}" height="{H}" fill="url(#g)"/>
  <g transform="translate({W / 2 - 56} 220) scale(7)"><path fill="#ffffff" d="{MARK}"/></g>
  <text x="{W / 2}" y="400" text-anchor="middle" fill="#ffffff" font-family="Inter"
        font-weight="300" font-size="52" letter-spacing="1">{os_name}</text>
  <text x="{W / 2}" y="985" text-anchor="middle" fill="#6e6e73" font-family="Inter"
        font-size="24">Arrow keys to choose, Enter to start</text>
</svg>"""


def label(text):
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{LABEL_W}" height="{LABEL_H}">
  <text x="4" y="{LABEL_H / 2 + 8}" fill="#ffffff" fill-opacity="0.92" font-family="Inter"
        font-size="22">{text}</text>
</svg>"""


def highlight_pieces(out):
    """Nine-slice highlight for the selected entry: rounded corners, stretchable edges."""
    corner = {
        "nw": f'<path d="M0 {R} A{R} {R} 0 0 1 {R} 0 V{R} Z" {HIGHLIGHT}/>',
        "ne": f'<path d="M0 0 A{R} {R} 0 0 1 {R} {R} H0 Z" {HIGHLIGHT}/>',
        "sw": f'<path d="M0 0 H{R} V{R} A{R} {R} 0 0 1 0 0 Z" {HIGHLIGHT}/>',
        "se": f'<path d="M0 0 H{R} A{R} {R} 0 0 1 0 {R} Z" {HIGHLIGHT}/>',
    }
    for name, shape in corner.items():
        render(f'<svg xmlns="http://www.w3.org/2000/svg" width="{R}" height="{R}">{shape}</svg>',
               out / f"select_{name}.png", R, R)
    for name, (w, h) in {"n": (1, R), "s": (1, R), "e": (R, 1), "w": (R, 1), "c": (1, 1)}.items():
        render(f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}">'
               f'<rect width="{w}" height="{h}" {HIGHLIGHT}/></svg>', out / f"select_{name}.png", w, h)


THEME = f"""# Kestrel OS boot menu theme. Generated by iso/live/grub_theme.py.
desktop-image: "background.png"
desktop-color: "#050506"
title-text: ""
# While GRUB loads the system after a choice, it shows its text area. Full screen and
# without a border it is just black, like the Mac between choosing and the boot screen.
terminal-left: "0"
terminal-top: "0"
terminal-width: "100%"
terminal-height: "100%"
terminal-border: "0"

+ boot_menu {{
    left = 50%-{LABEL_W // 2 + 16}
    width = {LABEL_W + 32}
    top = 47%
    height = 36%
    # The entry titles are a text fallback for when the theme fails; here they are hidden
    # (fully transparent) and the label images show instead.
    item_color = "#00000000"
    selected_item_color = "#00000000"
    item_height = {LABEL_H}
    item_padding = 12
    item_spacing = 8
    icon_width = {LABEL_W}
    icon_height = {LABEL_H}
    item_icon_space = 0
    selected_item_pixmap_style = "select_*.png"
    scrollbar = false
}}
"""


def main():
    out, os_name = Path(sys.argv[1]), sys.argv[2]
    (out / "icons").mkdir(parents=True, exist_ok=True)
    render(background(os_name), out / "background.png", W, H)
    highlight_pieces(out)
    for cls, text in ENTRIES.items():
        render(label(text.format(os=os_name)), out / "icons" / f"{cls}.png", LABEL_W, LABEL_H)
    (out / "theme.txt").write_text(THEME)


if __name__ == "__main__":
    main()
